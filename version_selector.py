def select_version(message,type,ec_level):
    global VERSION_LIMITS
    if type == "N":
        type_index = 0
    elif type == "A":
        type_index = 1
    else:
        type_index = 2
    
    limit_list = []
    for i in range (1,41):
        limit_list.append(VERSION_LIMITS[i][ec_level][type_index])
    
    version_number = -1
    for i in range(len(limit_list)):
        if limit_list[i] >= len(message):
            version_number = i+1
            break
    
    if version_number == -1:
        print("ERROR: Message too large")
        sys.exit()
    
    print(f"Using version {version_number}")
    return version_number

def select_type(message):
    numeric = "0123456789"
    alphanumeric = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:"
    if all(c in numeric for c in message):
        return "N"
    elif all(c in alphanumeric for c in message):
        return "A"
    elif all(ord(c) < 256 for c in message):
        return "B"
    else:
        print("ERROR: NOT ENCODABLE")
        sys.exit()